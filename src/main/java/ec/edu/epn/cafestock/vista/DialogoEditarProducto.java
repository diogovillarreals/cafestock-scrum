    public DialogoEditarProducto(
            java.awt.Frame parent,
            boolean modal,
            Producto producto,
            Consumer<Producto> alGuardar) {
        super(parent, modal);
        initComponents();
        this.productoOriginal = Objects.requireNonNull(
                producto,
                "El producto a editar no puede ser nulo."
        );
        this.alGuardar = alGuardar;
        cargarDatosProducto();
        setLocationRelativeTo(parent);
    }

    public Producto getProductoEditado() {
        return productoEditado;
    }

    private void cargarDatosProducto() {
        TxtFieldCodigo.setEditable(false);
        TxtFieldCodigo.setText(productoOriginal.getCodigo());
        TxtFieldNombre.setText(productoOriginal.getNombre());
        TxtFieldPrecio.setText(
                productoOriginal.getPrecio() != null
                        ? productoOriginal.getPrecio().toPlainString()
                        : ""
        );
        TxtFieldStockA.setText(Integer.toString(productoOriginal.getStockActual()));
        TxtFieldStockM.setText(Integer.toString(productoOriginal.getStockMinimo()));
    }

    private void cancelarEdicion() {
        productoEditado = null;
        dispose();
    }

    private void guardarCambios() {
        if (productoOriginal == null) {
            return;
        }

        try {
            Optional<Producto> resultado = ValidacionFormularioEdicion.validar(
                    this,
                    productoOriginal,
                    TxtFieldNombre.getText(),
                    TxtFieldPrecio.getText(),
                    TxtFieldStockA.getText(),
                    TxtFieldStockM.getText()
            );
            if (resultado.isEmpty()) {
                return;
            }
            Producto actualizado = resultado.get();

            if (alGuardar == null) {
                JOptionPane.showMessageDialog(
                        this,
                        "El formulario todavía no está conectado para guardar los cambios.",
                        "Edición no disponible",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            alGuardar.accept(actualizado);
            this.productoEditado = actualizado;

            JOptionPane.showMessageDialog(
                    this,
                    "Producto actualizado correctamente.",
                    "Edición guardada",
                    JOptionPane.INFORMATION_MESSAGE
            );
            dispose();

        } catch (IllegalArgumentException error) {
            JOptionPane.showMessageDialog(
                    this,
                    error.getMessage(),
                    "Datos inválidos",
                    JOptionPane.WARNING_MESSAGE
            );
        } catch (IllegalStateException error) {
            JOptionPane.showMessageDialog(
                    this,
                    error.getMessage(),
                    "No se pudo guardar",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }

