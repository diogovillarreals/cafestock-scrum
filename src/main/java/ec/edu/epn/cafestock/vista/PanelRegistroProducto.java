    private void guardarProducto() {
        try {
            String codigo = ValidarCampos.validarObligatorio(TxtCodigo.getText(), "Código");
            String nombre = ValidarCampos.validarObligatorio(TxtNombre.getText(), "Nombre");
            BigDecimal precio = ValidarCampos.validarPrecio(TxtPrecio.getText());
            int stockActual = ValidarCampos.validarStock(TxtStockActual.getText(), "Stock actual");
            int stockMinimo = ValidarCampos.validarStock(TxtStockMinimo.getText(), "Stock mínimo");

            Producto producto = new Producto(codigo, nombre, precio, stockActual, stockMinimo);

            if (alGuardar == null) {
                JOptionPane.showMessageDialog(
                        this,
                        "El formulario todavía no está conectado al almacenamiento.",
                        "Registro no disponible",
                        JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            alGuardar.accept(producto);

            JOptionPane.showMessageDialog(
                    this,
                    "Producto registrado correctamente.",
                    "Registro exitoso",
                    JOptionPane.INFORMATION_MESSAGE
            );
            limpiarCampos();

        } catch (IllegalArgumentException error) {
            JOptionPane.showMessageDialog(
                    this,
                    error.getMessage(),
                    "Datos inválidos",
                    JOptionPane.WARNING_MESSAGE
            );

        } catch (IllegalStateException error) {
            JOptionPane.showMessageDialog(
                    this,
                    error.getMessage(),
                    "No se pudo guardar",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
    public void limpiarCampos() {
        TxtCodigo.setText("");
        TxtNombre.setText("");
        TxtPrecio.setText("");
        TxtStockActual.setText("");
        TxtStockMinimo.setText("");
        TxtCodigo.requestFocusInWindow();
    }

